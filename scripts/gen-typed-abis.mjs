#!/usr/bin/env node
/**
 * Generate typed ABI modules from the exported ABI JSONs (#13).
 *
 * `src/abis/<Facet>.json` is what the monorepo's `exportAbis.sh` writes and
 * stays the source of truth. A JSON import is typed by TypeScript as a wide
 * array of objects, so viem cannot infer function names, argument lists or
 * return shapes from it — a contract signature change compiled cleanly and
 * failed only at run time (#12: `previewMatch` gained two arguments and every
 * match preview silently returned null). This writes each ABI again as
 * `src/abis/typed/<Facet>.ts`, `export default [...] as const`, which viem
 * types exactly, so the same change is a compile error.
 *
 *   node scripts/gen-typed-abis.mjs           write the typed modules
 *   node scripts/gen-typed-abis.mjs --check   exit 1 if any module is
 *                                             missing, stale or orphaned
 *
 * `--check` is what CI runs: a sync that updates the JSON without
 * regenerating cannot pass, and neither can a hand edit of a typed module.
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src', 'abis');
const OUT = join(SRC, 'typed');
const check = process.argv.includes('--check');

/** The exported ABIs: every JSON in src/abis except the provenance stamp. */
const sources = readdirSync(SRC)
  .filter((f) => f.endsWith('.json') && f !== '_source.json')
  .sort();
if (sources.length === 0) {
  console.error(`gen-typed-abis: no ABI JSON found in ${SRC}`);
  process.exit(1);
}

/** The exact text of one typed module. Deterministic, so `--check` can compare bytes. */
function render(file) {
  const abi = JSON.parse(readFileSync(join(SRC, file), 'utf8'));
  if (!Array.isArray(abi) || abi.length === 0) {
    throw new Error(`${file} is not a non-empty ABI array`);
  }
  return (
    `// GENERATED by scripts/gen-typed-abis.mjs from src/abis/${file} -- do not edit.\n` +
    `// Regenerate with \`npm run gen:abis\` after every ABI sync.\n` +
    `export default ${JSON.stringify(abi, null, 2)} as const;\n`
  );
}

/**
 * Every custom error in any exported facet ABI, de-duplicated by signature.
 * Facet ABIs list different error sets (a few hundred in most, a handful in
 * some), and a cross-facet call inside the Diamond passes the callee's revert
 * straight through. Appending this set to each facet ABI (src/abis/diamond.ts) lets viem
 * name any revert, not just the ones the called facet declares.
 */
/** Canonical ABI type, expanding tuples, so two errors share a key only when they encode alike. */
function canonical(param) {
  if (!param.type.startsWith('tuple')) return param.type;
  return `(${param.components.map(canonical).join(',')})${param.type.slice('tuple'.length)}`;
}

function renderErrors() {
  const seen = new Map();
  for (const f of sources) {
    for (const item of JSON.parse(readFileSync(join(SRC, f), 'utf8'))) {
      if (item.type !== 'error') continue;
      const sig = `${item.name}(${item.inputs.map(canonical).join(',')})`;
      if (!seen.has(sig)) seen.set(sig, item);
    }
  }
  const errors = [...seen.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([, e]) => e);
  return (
    `// GENERATED by scripts/gen-typed-abis.mjs from every src/abis/*.json -- do not edit.\n` +
    `// The de-duplicated union of the errors the exported facets declare.\n` +
    `export default ${JSON.stringify(errors, null, 2)} as const;\n`
  );
}

const expected = new Map(sources.map((f) => [`${basename(f, '.json')}.ts`, render(f)]));
expected.set('DiamondErrors.ts', renderErrors());
const present = existsSync(OUT) ? readdirSync(OUT).filter((f) => f.endsWith('.ts')) : [];

if (check) {
  const problems = [];
  for (const [name, text] of expected) {
    const path = join(OUT, name);
    if (!existsSync(path)) problems.push(`missing  src/abis/typed/${name}`);
    else if (readFileSync(path, 'utf8') !== text) problems.push(`stale    src/abis/typed/${name}`);
  }
  for (const name of present) {
    if (!expected.has(name)) problems.push(`orphaned src/abis/typed/${name} (no matching JSON)`);
  }
  if (problems.length > 0) {
    console.error('gen-typed-abis: the typed ABI modules do not match src/abis/*.json:');
    for (const p of problems) console.error(`  ${p}`);
    console.error('Run `npm run gen:abis` and commit the result.');
    process.exit(1);
  }
  console.log(`gen-typed-abis: ${expected.size} typed ABI modules match their JSON.`);
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [name, text] of expected) writeFileSync(join(OUT, name), text);
  for (const name of present) {
    if (!expected.has(name)) {
      console.error(`gen-typed-abis: src/abis/typed/${name} has no matching JSON -- delete it`);
      process.exitCode = 1;
    }
  }
  console.log(`gen-typed-abis: wrote ${expected.size} typed ABI modules to src/abis/typed/.`);
}
